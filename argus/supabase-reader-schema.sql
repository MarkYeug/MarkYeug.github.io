-- Run this in the Supabase SQL Editor for the Argus reader.
-- The browser uses only the project's anon/public key; row-level security protects user data.

create table if not exists public.reader_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  chapter_number numeric not null,
  scroll_percent integer not null default 0 check (scroll_percent between 0 and 100),
  updated_at timestamptz not null default now(),
  primary key (user_id, chapter_number)
);

create table if not exists public.reader_comments (
  id bigint generated by default as identity primary key,
  chapter_number numeric not null,
  paragraph_id text,
  user_id uuid not null references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 1 and 40),
  body text not null check (char_length(body) between 1 and 3000),
  created_at timestamptz not null default now()
);

create index if not exists reader_comments_chapter_created_idx
  on public.reader_comments (chapter_number, created_at);
create index if not exists reader_comments_paragraph_idx
  on public.reader_comments (chapter_number, paragraph_id);

alter table public.reader_progress enable row level security;
alter table public.reader_comments enable row level security;

drop policy if exists "Readers can view their own progress" on public.reader_progress;
create policy "Readers can view their own progress"
  on public.reader_progress for select to authenticated
  using (auth.uid() = user_id);

drop policy if exists "Readers can insert their own progress" on public.reader_progress;
create policy "Readers can insert their own progress"
  on public.reader_progress for insert to authenticated
  with check (auth.uid() = user_id);

drop policy if exists "Readers can update their own progress" on public.reader_progress;
create policy "Readers can update their own progress"
  on public.reader_progress for update to authenticated
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Comments are publicly readable" on public.reader_comments;
create policy "Comments are publicly readable"
  on public.reader_comments for select to anon, authenticated
  using (true);

drop policy if exists "Signed-in readers can comment as themselves" on public.reader_comments;
create policy "Signed-in readers can comment as themselves"
  on public.reader_comments for insert to authenticated
  with check (
    auth.uid() = user_id
    and char_length(trim(body)) between 1 and 3000
    and char_length(trim(display_name)) between 1 and 40
  );

drop policy if exists "Readers can delete their own comments" on public.reader_comments;
create policy "Readers can delete their own comments"
  on public.reader_comments for delete to authenticated
  using (auth.uid() = user_id);

grant select, insert, update on public.reader_progress to authenticated;
grant select on public.reader_comments to anon, authenticated;
grant insert, delete on public.reader_comments to authenticated;
grant usage, select on sequence public.reader_comments_id_seq to authenticated;
